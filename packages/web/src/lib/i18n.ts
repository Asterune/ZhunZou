const messages: Record<Locale, Record<string, string>> = { en, zh };

function isLocale(value: string | null | undefined): value is Locale {
  return value === 'zh' || value === 'en';
}

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'zh';

  try {
    const saved = window.localStorage?.getItem(STORAGE_KEY);
    if (isLocale(saved)) return saved;
  } catch {
    // Private browsing may deny storage; fall back to the browser language.
  }

  const language = `${window.navigator?.language ?? ''}`.toLowerCase();
  return language.startsWith('zh') ? 'zh' : 'en';
}

export const locale = ref<Locale>(detectLocale());

export function setLocale(next: Locale): void {
  locale.value = next;

  if (typeof window !== 'undefined') {
    try {
      window.localStorage?.setItem(STORAGE_KEY, next);
    } catch {
      // Ignore storage failures.
    }
  }

  if (typeof document !== 'undefined') {
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
    document.title =
      next === 'zh' ? '准奏 · Agent 决策中枢' : 'Zhunzou · Decision hub for AI agents';
  }
}

export function toggleLocale(): void {
  setLocale(locale.value === 'zh' ? 'en' : 'zh');
}

/** Apply the stored/browser language once the app boots. */
export function initI18n(): void {
  setLocale(detectLocale());
}

/** Translate a key, interpolating `{name}` placeholders. */
export function t(
  key: string,
  params?: Record<string, string | number>,
): string {
  const table = messages[locale.value] ?? messages.en;
  let text = table[key] ?? messages.en[key] ?? key;

  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }

  return text;
}

export function useI18n() {
  return {
    locale: readonly(locale),
    t,
    setLocale,
    toggleLocale,
  };
}
