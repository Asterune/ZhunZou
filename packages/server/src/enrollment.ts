import { randomBytes } from 'node:crypto';

import { hashToken } from './auth.js';

/**
 * Human-friendly alphabet: no 0/O/1/I, so codes can be read over a call.
 * 10 characters ≈ 49 bits of entropy, which is plenty for a 15-minute,
 * single-use code protected by a per-IP attempt limit.
 */
const CODE_ALPHABET = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
const CODE_LENGTH = 10;

/** Strip the display dashes/spaces and normalize case before hashing. */
export function normalizeEnrollmentCode(raw: string): string {
  return raw.replace(/[\s-]+/g, '').toUpperCase();
}

export function hashEnrollmentCode(raw: string): string {
  return hashToken(normalizeEnrollmentCode(raw));
}

/** `ABCDE-FGHIJ` — easier to read and retype than one long string. */
export function generateEnrollmentCode(): string {
  const bytes = randomBytes(CODE_LENGTH);
  let code = '';
  for (let index = 0; index < CODE_LENGTH; index += 1) {
    code += CODE_ALPHABET[bytes[index]! % CODE_ALPHABET.length];
  }
  return `${code.slice(0, 5)}-${code.slice(5)}`;
}

/** `MacBook Pro` → `macbook-pro`, used when the code has no env hint. */
export function slugifyHost(raw: string | undefined): string {
  return (raw ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
}

const CLIENT_PREFIXES: Record<string, string> = {
  cursor: 'cursor',
  opencode: 'opencode',
  'claude-code': 'claude',
  codex: 'codex',
  gemini: 'gemini',
  qoder: 'qoder',
  windsurf: 'windsurf',
  other: 'agent',
};

/** Short, stable suffix for `公司-<client>` when several clients share a code. */
export function clientPrefix(kind: string): string {
  return CLIENT_PREFIXES[kind] ?? 'agent';
}

/**
 * Small in-memory brute-force guard for the public exchange endpoint.
 * Single-process deployment is an explicit design constraint of the hub, so a
 * Map is enough; restarting the server only resets the window.
 */
export interface EnrollmentRateLimiter {
  /** Returns false when this key has exhausted its budget. */
  allow(key: string, now?: number): boolean;
  /** Called after a successful exchange so normal users are never throttled. */
  reset(key: string): void;
}

export function createEnrollmentRateLimiter(
  limit = 12,
  windowMs = 10 * 60 * 1000,
): EnrollmentRateLimiter {
  const buckets = new Map<string, { count: number; resetAt: number }>();

  function sweep(now: number): void {
    if (buckets.size < 512) return;
    for (const [key, bucket] of buckets) {
      if (bucket.resetAt <= now) buckets.delete(key);
    }
  }

  return {
    allow(key, now = Date.now()) {
      sweep(now);
      const bucket = buckets.get(key);
      if (!bucket || bucket.resetAt <= now) {
        buckets.set(key, { count: 1, resetAt: now + windowMs });
        return true;
      }
      if (bucket.count >= limit) return false;
      bucket.count += 1;
      return true;
    },
    reset(key) {
      buckets.delete(key);
    },
  };
}

export interface InstallScriptOptions {
  /** Public origin of the hub, without a trailing slash. */
  hubUrl: string;
  /** Plaintext code baked into the served script (may be empty). */
  code: string;
}

