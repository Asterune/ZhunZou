export function renderInstallScript(
  kind: 'sh' | 'ps1',
  options: InstallScriptOptions,
): string {
  const hubUrl = options.hubUrl.replace(/\/+$/, '');
  const code = options.code.trim();
  const template = kind === 'sh' ? UNIX_TEMPLATE : POWERSHELL_TEMPLATE;
  return template
    .split('__HUB__')
    .join(hubUrl)
    .split('__CODE__')
    .join(code);
}
